export function adhkarFor(period) {
  return ADHKAR.filter(a => !a.only || a.only === period).map(a => ({
    id: a.id,
    title: a.title || '',
    text: a.text || (period === 'morning' ? a.textMorning : a.textEvening),
    count: a.count,
    source: a.source,
    fadl: a.fadl || (period === 'morning' ? a.fadlMorning : a.fadlEvening) || '',
    istighfar: !!a.istighfar
  }));
}

